/* ---------- TAMPILAN KOSONG ---------- */

function renderEmpty() {

  container.innerHTML = "";

  pagination.innerHTML = "";

  const box = document.createElement("div");

  box.className = "no-result";

  const message = document.createElement("p");

  message.textContent =
    `Tidak ada properti untuk "${searchInput.value.trim()}".`;

  const button = document.createElement("button");

  button.type = "button";

  button.textContent = "Hapus pencarian";

  button.onclick = clearSearch;

  box.appendChild(message);

  box.appendChild(button);

  container.appendChild(box);

}


/* ---------- RENDER PROPERTI ---------- */

function renderPage(page) {

  if (filtered.length === 0) {

    renderEmpty();

    return;

  }

  container.innerHTML = "";

  const start = (page - 1) * itemsPerPage;

  const end = start + itemsPerPage;

  filtered.slice(start, end).forEach((item, index) => {

    const card = document.createElement("div");

    card.className = "property-card";

    card.innerHTML = `
      <div class="thumbnail-wrapper">

        <img
          src="${item.thumbnail}"
          alt="${item.judul}"
          loading="lazy"
        >

      </div>

      <div class="property-content">

        <h3>${item.judul}</h3>

        <div class="price">${item.harga}</div>

        ${generateDetail(item)}

        <div class="btn-row">

          <a
            href="${item.video}"
            target="_blank"
            rel="noopener noreferrer"
            class="video-btn"
          >▶ Lihat Video</a>

          <a
            href="https://wa.me/6287737447313?text=${encodeURIComponent("Saya tertarik dengan properti: " + item.judul)}"
            target="_blank"
            rel="noopener noreferrer"
            class="whatsapp-btn"
          >Hubungi WhatsApp</a>

        </div>

      </div>
    `;

    container.appendChild(card);

    setTimeout(() => {

      card.classList.add("show");

    }, 100 * index);

  });

  renderPagination();

}


/* ---------- PAGINATION ---------- */

function renderPagination() {

  pagination.innerHTML = "";

  const totalPages = Math.ceil(
    filtered.length / itemsPerPage
  );

  for (let i = 1; i <= totalPages; i++) {

    const button = document.createElement("button");

    button.innerText = i;

    button.className = "page-btn";

    if (i === currentPage) {

      button.classList.add("active");

    }

    button.onclick = () => {

      currentPage = i;

      renderPage(i);

      document.getElementById("property").scrollIntoView({

        behavior: "smooth",

        block: "start"

      });

    };

    pagination.appendChild(button);

  }

}


